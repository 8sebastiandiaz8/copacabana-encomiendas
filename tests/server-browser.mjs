import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
page.setDefaultTimeout(120000); page.setDefaultNavigationTimeout(120000);
await page.context().grantPermissions(['geolocation']);
await page.context().setGeolocation({latitude:-16.5,longitude:-68.15,accuracy:10});
await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')}));
const errors = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto("http://127.0.0.1:8766/sistema.html", { waitUntil: "networkidle" });
  await page.getByLabel("Usuario", { exact: true }).fill("browser-test");
  await page.getByLabel("Contraseña", { exact: true }).fill("Browser-test-123!");
  await page.getByRole("button", { name: "Iniciar sesión" }).click();
  await page.getByRole("heading", { name: "Tu operación, de un vistazo." }).waitFor();
  assert.equal(await page.locator("#mode-banner").isVisible(), false);
  await page.getByRole("button", { name: "Nueva encomienda" }).click();
  await page.getByLabel("Sucursal de origen").selectOption("1");
  await page.getByLabel("Sucursal de destino").selectOption("2");
  await page.getByLabel("Descripción del contenido").fill("Registro de integración con Python");
  await page.getByLabel("Nombre del remitente").fill("Prueba remitente");
  await page.getByLabel("Nombre del destinatario").fill("Prueba destinatario");
  await page.getByLabel("Documento del remitente").fill("PRUEBA-1");
  await page.getByLabel("Documento del destinatario").fill("PRUEBA-2");
  await page.getByRole("button", { name: "Registrar encomienda" }).click();
  await page.locator("#modal").waitFor({ state: "hidden" });
  await page.reload();
  await page.getByText("Registro de integración con Python", { exact: true }).waitFor();
  assert.equal(await page.locator("tbody tr").count(), 1);
  const api = await page.evaluate(async () => (await fetch("/api/data")).json());
  assert.equal(api.shipments.length, 1);
  assert.ok(!("sender_ci" in api.shipments[0]));
  await page.screenshot({ path: "test-results/python-dashboard.png", fullPage: true });
  await page.getByRole('link', {name:'Mapa y GPS',exact:true}).click();
  await page.getByRole('heading',{name:'Mapa y GPS',exact:true}).waitFor();
  await page.getByLabel('Vehículo',{exact:true}).selectOption('1');
  const sent = page.waitForResponse(r => r.url().endsWith('/api/vehicles/1/location') && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Compartir ubicación',exact:true}).click();
  assert.equal((await sent).status(),200);
  await page.waitForFunction(() => document.querySelector('#gps-status')?.textContent.includes('Compartiendo'));
  const stop = page.waitForResponse(r => r.url().endsWith('/location/stop'));
  await page.getByRole('button',{name:'Detener',exact:true}).click();
  assert.equal((await stop).status(),200);
  const locations = await page.evaluate(async () => (await fetch('/api/gps/locations')).json());
  assert.equal(locations.locations[0].active,0);
  assert.equal(locations.locations[0].latitude,-16.5);
  await page.getByRole('button',{name:'Gestionar dispositivos'}).click();
  await page.getByLabel('Nombre del dispositivo').fill('GPS integración');
  await page.getByRole('button',{name:'Crear clave de conexión'}).click();
  await page.locator('#gps-token').waitFor();
  const token = await page.locator('#gps-token').inputValue();
  assert.ok(token.startsWith('cpgps_'));
  await page.getByRole('button',{name:'Cerrar dispositivos'}).click();
  assert.equal(await page.locator('#gps-token').count(),0);
  await page.getByRole('button',{name:'Gestionar dispositivos'}).click();
  page.once('dialog', d=>d.accept());
  await page.getByRole('button',{name:'Revocar',exact:true}).click();
  await page.getByText('Todavía no hay dispositivos conectados.').waitFor();
  await page.getByRole('button',{name:'Cerrar dispositivos'}).click();
  await page.screenshot({path:'test-results/python-map.png',fullPage:true});
  await page.getByRole("button", { name: "Cambiar sesión" }).click();
  await page.getByRole("button", { name: "Iniciar sesión" }).waitFor();
  assert.equal(await page.evaluate(async () => (await fetch("/api/data")).status), 401);
  assert.deepEqual(errors, []);
  console.log("PASS: sesión real, CSRF, registro en Python, persistencia SQLite, documentos ocultos GPS del teléfono, creación/revocación de dispositivo y cierre de sesión.");
} finally { await browser.close(); }
